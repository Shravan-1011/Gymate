/*
 * ========================================
 * SPECIES INDEX (by id)
 * ========================================
 *
 * Built once, reused everywhere. Avoids
 * scanning the array on every lookup.
 * ========================================
 */

const speciesById: Record<string, PokemonSpecies> = {};

for (const species of pokemonSpecies) {
  speciesById[species.id] = species;
}

export function getPokemonSpeciesById(
  speciesId: string
): PokemonSpecies | null {
  return speciesById[speciesId] ?? null;
}

export function getStarterSpecies(): PokemonSpecies[] {
  return pokemonSpecies.filter(
    (species) => species.isStarter
  );
}

export function getSpeciesByRarity(
  rarity: PokemonSpecies['rarity']
): PokemonSpecies[] {
  return pokemonSpecies.filter(
    (species) => species.rarity === rarity
  );
}

/*
 * ========================================
 * CATCHABLE SPECIES BY BALL CATCH RULE
 * ========================================
 *
 * See PokeballCatchRule in types/pokemon.ts
 * for what each rule means. Excludes
 * starters and mega forms unconditionally
 * — neither is ever obtainable from a
 * ball roll.
 * ========================================
 */

export function getCatchableSpeciesByRule(
  catchRule:
    | 'basic_form'
    | 'short_final_form'
    | 'mid_evolution_form'
    | 'legendary'
): PokemonSpecies[] {
  return pokemonSpecies.filter((species) => {
    if (species.isStarter) {
      return false;
    }

    if (species.isMegaForm) {
      return false;
    }

    switch (catchRule) {
      /*
       * Poké Ball:
       * Common, Stage 1 only.
       */
      case 'basic_form':
        return (
          species.evolutionStage === 1 &&
          species.rarity === 'common'
        );

      /*
       * Great Ball:
       * Uncommon, Stage 1 only.
       */
      case 'short_final_form':
        return (
          species.evolutionStage === 1 &&
          species.rarity === 'uncommon'
        );

      /*
       * Ultra Ball:
       * Rare, Stage 1 only.
       */
      case 'mid_evolution_form':
        return (
          species.evolutionStage === 1 &&
          species.rarity === 'rare'
        );

      /*
       * Master Ball:
       * Legendary Pokémon.
       *
       * Legendary Pokémon can be one-stage
       * Pokémon, so evolutionStage is not
       * used here.
       */
      case 'legendary':
        return (
          species.rarity === 'legendary'
        );

      default:
        return false;
    }
  });
}

/*
 * ========================================
 * DEX TOTAL (for Pokédex completion %)
 * ========================================
 *
 * Excludes starters (received, not
 * "caught") and mega forms (a permanent
 * upgrade of an existing species, not a
 * separate dex entry) from the
 * completion denominator.
 * ========================================
 */

export function getDexCompletionTotal(): number {
  return pokemonSpecies.filter(
    (species) =>
      !species.isStarter &&
      !species.isMegaForm
  ).length;
}
